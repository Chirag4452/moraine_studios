export const DEFAULT_CURRENCY = CURRENCIES[0]; // INR

export function findCurrencyByCode(code: string): CurrencyItem | undefined {
  const upper = code.trim().toUpperCase();
  return CURRENCIES.find((c) => c.code === upper);
}

export function findCurrencyByCountryCode(countryCode: string): CurrencyItem | undefined {
  const upper = countryCode.trim().toUpperCase();
  return CURRENCIES.find((c) => c.countryCode === upper);
}

export function formatCurrencyPrice(inrPrice: number, currency: CurrencyItem): string {
  if (currency.code === "INR") {
    return `Rs. ${inrPrice.toLocaleString("en-IN", {
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    })}`;
  }

  const converted = inrPrice * currency.rateFromINR;
  const decimals = currency.decimals !== undefined ? currency.decimals : 2;

  const formattedNumber = converted.toLocaleString("en-US", {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  });

  if (currency.symbolPosition === "after") {
    return `${formattedNumber} ${currency.symbol.trim()}`;
  }
  return `${currency.symbol}${formattedNumber}`;
}
